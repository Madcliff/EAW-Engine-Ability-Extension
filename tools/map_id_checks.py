"""Map every one-byte ability-id bound the expansion raises, so they can be widened to 32-bit compares.

usage: python3 -I map_id_checks.py STOCK_StarWarsG.exe DISASSEMBLY.txt OUT_DOC.md OUT_HEADER.h
  DISASSEMBLY.txt = llvm-objdump -d --no-show-raw-insn of the stock exe.
For each site: the instructions from the bound instruction until at least 5 bytes are covered (room for a jmp rel32),
their bytes, the position of the imm8, relative branches, and whether any other branch in the exe lands inside the
covered bytes (then the site cannot be relocated safely). Writes a markdown table and a C table (exp_wide_sites.h)."""
import re, struct, sys, bisect

exe, dis, out_md, out_h = sys.argv[1:5]
b = open(exe, 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]; opt = pe + 24
nsec = struct.unpack_from('<H', b, pe + 6)[0]; st = opt + struct.unpack_from('<H', b, pe + 20)[0]
secs = [struct.unpack_from('<IIII', b, st + 40 * i + 8) for i in range(nsec)]
def off(r):
    for vs, va, rs, rp in secs:
        if va <= r < va + max(vs, rs): return rp + r - va
BASE = 0x140000000

# group, rva of the bound instruction, offset of imm8 in it, how the new bound is computed (documentation)
SITES = []
EXP_RAISE = [0x035e6d, 0x035f3b, 0x036098, 0x037969, 0x037a2d, 0x037b0d, 0x044de2, 0x0a2e4c,
    0x2e0583, 0x2e074f, 0x2e0937, 0x2f927c, 0x2f93fc, 0x2f957c, 0x2f96fc,
    0x38a38a, 0x397da4, 0x398042, 0x398080, 0x3984af, 0x3986c8, 0x398c6b, 0x398ef7,
    0x39b4a0, 0x39b977, 0x3a3e34, 0x42997b, 0x429dc7, 0x429e7f,
    0x42f37a, 0x42f6a3, 0x42f713, 0x42f7a3, 0x42f7e3, 0x42f893, 0x42f8e3, 0x42fa77, 0x42faea, 0x42fb82, 0x42fdf3,
    0x430323, 0x4378e8, 0x57f4a3, 0x57ffe4, 0x63640a]
for r in EXP_RAISE:
    SITES.append(('range check', r, 3 if b[off(r)] == 0x41 else 2, 'stock + N'))
for r in (0x42ed9, 0x43317, 0x43386):
    SITES.append(('order dispatcher', r, 6, 'top id + 1'))
for name, r, io in (('switch slot walk', 0x3984b8, 2), ('switch has ability', 0x3986d1, 2), ('switch activation', 0x38a532, 2),
                    ('switch can activate', 0x39b640, 2), ('switch targeting', 0x2e0aec, 2), ('switch order dispatcher', 0x4366e, 4),
                    ('switch button click', 0x346eea, 2)):
    SITES.append((name, r, io, 'stock + N'))
for r, io, tm in ((0x3848fe, 2, 1), (0x384958, 2, 1), (0x42f48a, 2, 1), (0x43ec19, 3, 0), (0x43eca8, 3, 0),
                  (0x43f007, 2, 0), (0x43f398, 3, 0), (0x43f6f7, 3, 0)):
    SITES.append(('per-type remap', r, io, 'top id - %d' % tm))
for r in (0x562b87, 0x562c7b):
    SITES.append(('countdown save fold (add)', r, 3, '(8 + 4M) / 4'))
SITES.append(('countdown update loop', 0x42fa20, 2, 'M = 0x4d + N'))
SITES.append(('card layout loop', 0x31d07f, 3, 'M = 0x4d + N'))

# instruction starts and lengths from the disassembly; every branch target
starts, text = [], {}
targets = set()
for line in open(dis, errors='replace'):
    m = re.match(r'\s*([0-9a-f]{9,}):\s+(\S.*)$', line)
    if not m: continue
    a = int(m.group(1), 16) - BASE; ins = m.group(2).strip()
    starts.append(a); text[a] = ins
    t = re.match(r'(j\w+|callq|loop\w*)\s+0x([0-9a-f]+)', ins)
    if t: targets.add(int(t.group(2), 16) - BASE)
starts.sort()
def nxt(a):
    i = bisect.bisect_right(starts, a)
    return starts[i]

rows, centries, bad = [], [], 0
for grp, r, io, rule in SITES:
    insns, a = [], r
    while sum(l for _, l in insns) < 5:
        n = nxt(a); insns.append((a, n - a)); a = n
    total = a - r
    raw = b[off(r):off(r) + total]
    inner = sorted(t for t in targets if r < t < r + total)
    imm = raw[io]
    first = raw[:insns[0][1]]
    ok_op = (first[0] == 0x83) or (first[0] in (0x41, 0x48, 0x49, 0x4c, 0x4d) and first[1] == 0x83)
    # classify the following instructions
    kinds = []
    for (ia, il) in insns[1:]:
        ib = b[off(ia):off(ia) + il]
        if il == 2 and 0x70 <= ib[0] <= 0x7f: kinds.append('jcc8')
        elif il == 6 and ib[0] == 0x0f and 0x80 <= ib[1] <= 0x8f: kinds.append('jcc32')
        elif il == 2 and ib[0] == 0xeb: kinds.append('jmp8')
        elif il == 5 and ib[0] == 0xe9: kinds.append('jmp32')
        elif 'rip' in text[ia] or text[ia].startswith(('call', 'j', 'loop', 'ret')): kinds.append('UNSUPPORTED')
        else: kinds.append('plain')
    safe = ok_op and not inner and 'UNSUPPORTED' not in kinds
    if not safe: bad += 1
    rows.append('| %s | 0x%x | %s | 0x%02x | %s | %d | %s | %s |' % (grp, BASE + r, ' ; '.join(text[x] for x, _ in insns),
                imm, rule, total, ','.join(kinds) or '-', 'yes' if safe else 'NO (%s)' % ('inner branch target' if inner else 'form')))
    centries.append('    { 0x%06x, %d, %d, %d, "%s" },   /* %s: %s */' % (r, io, insns[0][1], total, raw.hex(), grp, text[r]))

with open(out_md, 'w') as f:
    f.write('# Ability-id bounds raised by the expansion (stock StarWarsG.exe 1.121.859328)\n\n')
    f.write('Generated by Engine_Patch_Master/tools/map_id_checks.py. Every site compares an ability id (or a count derived\n'
            'from the id range) against a one-byte immediate. The expansion raises the immediate in place, which caps the\n'
            'bound at 0x7f (signed imm8). Widening: the bound instruction plus what follows it (at least 5 bytes) are\n'
            'replaced by `jmp stub`; the stub runs the same instruction with a 32-bit immediate (opcode 0x83 -> 0x81),\n'
            're-targets the relative branches and jumps back. "Relocatable" = no other branch lands inside the bytes.\n\n')
    f.write('Sites: %d, not relocatable: %d\n\n' % (len(SITES), bad))
    f.write('| group | address | instructions replaced | stock imm | new bound | bytes | follow-up kinds | relocatable |\n|---|---|---|---|---|---|---|---|\n')
    f.write('\n'.join(rows) + '\n')
with open(out_h, 'w') as f:
    f.write('/* generated by tools/map_id_checks.py - one-byte ability-id bounds that can be widened to imm32 */\n')
    f.write('typedef struct { u32 rva; int imm_off, len1, total; const char *stock; } wide_site;\n')
    f.write('static const wide_site WIDE_SITES[] = {\n' + '\n'.join(centries) + '\n};\n')
    f.write('#define N_WIDE_SITES %d\n' % len(SITES))
print(len(SITES), 'sites,', bad, 'not relocatable')
