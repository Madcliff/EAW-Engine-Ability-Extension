#!/usr/bin/env python3
"""Writes patch_data.h for the DLL from ../patch_starwarsg.py (run from anywhere: python3 gen_patch_data.py)."""
import os, struct, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import patch_starwarsg as p
IB = 0x140000000
def arr(b): return ','.join('0x%02x' % x for x in b)
def target(packed): return struct.unpack('<Q', packed)[0]
o = ["/* generated by gen_patch_data.py from patch_starwarsg.py - do not edit by hand */",
     "#define STOCK_SIZE_OF_IMAGE 0x%xu" % p.SIZE_OF_IMAGE_OLD,
     "#define CAVE_RVA 0x%xu" % (p.CAVE_VA - IB),
     "#define ZZ_RVA 0x%xu" % p.ZZ_VA_RVA,
     "#define TEXT_END_RVA 0x%xu" % (0x1000 + p.TEXT_VSIZE_OLD),
     "#define ZZ_CARD_FN_RVA 0x%xu" % (p.ZZ_CARD_FN - IB),
     "#define ZZ_WIDE_RVA 0x%xu" % (p.ZZ_WIDE - IB),
     "static const unsigned char CAVE[%d]={%s};" % (len(p.CAVE), arr(p.CAVE)),
     "static const unsigned char ZZ_CODE[%d]={%s};" % (len(p.ZZ_CODE), arr(p.ZZ_CODE)),
     "typedef struct { unsigned rva; unsigned len; const unsigned char *orig; const unsigned char *new_; } code_patch;",
     "typedef struct { unsigned rva; unsigned old_target_rva; unsigned new_target_rva; } data_patch; /* old 0 = empty slot */"]
for i, (va, ob, nb, d) in enumerate(p.PATCHES):
    o.append("static const unsigned char P%d_O[]={%s}, P%d_N[]={%s}; /* %s */" % (i, arr(ob), i, arr(nb), d))
o.append("static const code_patch PATCHES[%d]={%s};" % (len(p.PATCHES), ','.join(
    "{0x%x,%d,P%d_O,P%d_N}" % (va - IB, len(ob), i, i) for i, (va, ob, nb, d) in enumerate(p.PATCHES))))
data = []
for va, ob, nb in p.DATA_PATCHES + p.DLL_ONLY_DATA_PATCHES:
    old, new = target(ob), target(nb)
    data.append("{0x%x,0x%x,0x%x}" % (va - IB, old - IB if old else 0, new - IB))
o.append("static const data_patch DATA_PATCHES[%d]={%s};" % (len(data), ','.join(data)))
# component-table relocation: every instruction that addresses the stock table (rip-relative, 7 bytes,
# disp32 at +3) and the binding loop's entry count (cmp edi,965 at 0x140347deb, imm32 at +2)
import json
refs = json.load(open(os.path.join(HERE, 'table_refs.json')))
o.append("#define COMP_TABLE_RVA 0xa174e0u")
o.append("#define COMP_TABLE_COUNT 965u")
o.append("#define COMP_COUNT_IMM_RVA 0x347dedu")
o.append("typedef struct { unsigned rva; unsigned table_off; } table_ref;")
o.append("static const table_ref TABLE_REFS[%d]={%s};" % (len(refs), ','.join("{0x%x,0x%x}" % (r['rva'], r['table_off']) for r in refs)))
out = os.path.join(HERE, 'patch_data.h')
open(out, 'w').write('\n'.join(o) + '\n')
print('wrote', out, '-', len(p.PATCHES), 'code patches,', len(data), 'table slots, zz code', len(p.ZZ_CODE), 'bytes')
